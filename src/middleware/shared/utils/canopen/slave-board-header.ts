/**
 * The firmware headers of a CANopen slave on a board: `canopen_slave_config.h` (settings, always
 * written on a board target) and `canopen_slave_od.h` (the object dictionary in CANopenNode's
 * static form, written only when a slave is on). The dictionary has the same objects, defaults
 * and attributes the runtime's `slave_od.cpp` builds from a `devices` item of conf/canopen.json.
 */

import type { CanopenSlaveConfig, CanopenSlaveDataType, CanopenSlaveObject } from '../../ports/canopen-types'
import { canopenTypeBits } from './data-types'
import { isSlavePacked, isSlaveString, SLAVE_PDO_COUNT, slaveObjectBytes, type SlavePdo, slavePdoLayout } from './slave'
import type { CanopenSlaveBoardProfile } from './slave-board'

/** The stub's content: no slave. */
export const CANOPEN_SLAVE_CONFIG_DISABLED = [
  '// Generated by OpenPLC Editor: no CANopen slave on this board.',
  '#ifndef CANOPEN_SLAVE_CONFIG_H',
  '#define CANOPEN_SLAVE_CONFIG_H',
  '',
  '#define CANOPEN_SLAVE_ENABLED 0',
  '',
  '#endif // CANOPEN_SLAVE_CONFIG_H',
  '',
].join('\n')

// CiA 301 attribute bits of CANopenNode (301/CO_ODinterface.h, OD_attributes_t).
const R = 0x01
const RW = 0x03
const TPDO = 0x04
const RPDO = 0x08
const MB = 0x40
const STR = 0x80

const COB_INVALID = 0x80000000

/** Type codes the firmware module reads (canopen_slave.cpp). */
const TYPE_CODE: Readonly<Record<CanopenSlaveDataType, number>> = {
  INTEGER8: 1,
  INTEGER16: 1,
  INTEGER32: 1,
  INTEGER64: 1,
  UNSIGNED8: 0,
  UNSIGNED16: 0,
  UNSIGNED32: 0,
  UNSIGNED64: 0,
  REAL32: 2,
  REAL64: 3,
  VISIBLE_STRING: 4,
}

interface Sub {
  sub: number
  attr: number
  value: Uint8Array
}

interface Entry {
  index: number
  record: boolean
  subs: Sub[]
}

interface Located {
  area: 'I' | 'Q'
  size: 'X' | 'B' | 'W' | 'D' | 'L'
  index: number
  bit: number
}

function le(value: bigint, bytes: number): Uint8Array {
  const out = new Uint8Array(bytes)
  let v = BigInt.asUintN(bytes * 8, value)
  for (let i = 0; i < bytes; i++) {
    out[i] = Number(v & 0xffn)
    v >>= 8n
  }
  return out
}

const u8 = (v: number): Uint8Array => le(BigInt(v), 1)
const u16 = (v: number): Uint8Array => le(BigInt(v), 2)
const u32 = (v: number): Uint8Array => le(BigInt(v >>> 0), 4)

/** The raw little-endian bytes of a value text of the type (0 for a text that does not parse). */
export function slaveRawBytes(text: string, dataType: CanopenSlaveDataType): Uint8Array {
  if (dataType === 'VISIBLE_STRING') return new Uint8Array([...text].map((c) => c.charCodeAt(0) & 0x7f))
  const bytes = canopenTypeBits(dataType) / 8
  const t = text.trim()
  if (dataType === 'REAL32' || dataType === 'REAL64') {
    const v = Number(t)
    const buf = new DataView(new ArrayBuffer(bytes))
    if (dataType === 'REAL32') buf.setFloat32(0, Number.isFinite(v) ? v : 0, true)
    else buf.setFloat64(0, Number.isFinite(v) ? v : 0, true)
    return new Uint8Array(buf.buffer)
  }
  let big = 0n
  if (/^[-+]?\d+$/.test(t) || /^0x[0-9a-f]+$/i.test(t)) big = BigInt(t)
  return le(big, bytes)
}

/** `%IW3`, `%QX0.2`: the parts the firmware finds the program's variable by; null when it is none. */
export function parseSlaveLocation(text: string): Located | null {
  const m = /^%([IQ])([XBWDL])(\d+)(?:\.(\d+))?$/.exec(text.trim().toUpperCase())
  if (!m) return null
  const size = m[2] as Located['size']
  if ((size === 'X') !== (m[4] !== undefined)) return null
  return { area: m[1] as Located['area'], size, index: Number(m[3]), bit: m[4] !== undefined ? Number(m[4]) : 0 }
}

function commEntries(config: CanopenSlaveConfig, pdos: { rpdos: SlavePdo[]; tpdos: SlavePdo[] }): Entry[] {
  const out: Entry[] = []
  const v = (index: number, attr: number, value: Uint8Array): void => {
    out.push({ index, record: false, subs: [{ sub: 0, attr, value }] })
  }
  const rec = (index: number, subs: Sub[]): void => {
    out.push({ index, record: true, subs })
  }
  v(0x1000, R | MB, u32(0))
  v(0x1001, R | TPDO, u8(0))
  rec(0x1003, [
    { sub: 0, attr: RW, value: u8(0) },
    ...[1, 2, 3, 4, 5, 6, 7, 8].map((sub) => ({ sub, attr: R | MB, value: u32(0) })),
  ])
  v(0x1005, RW | MB, u32(0x80))
  v(0x1006, RW | MB, u32(0))
  v(0x1007, RW | MB, u32(0))
  if (config.deviceName !== '') v(0x1008, R | STR, slaveRawBytes(config.deviceName, 'VISIBLE_STRING'))
  if (config.softwareVersion !== '') v(0x100a, R | STR, slaveRawBytes(config.softwareVersion, 'VISIBLE_STRING'))
  v(0x1014, RW | MB, u32(0x80))
  const watch = config.masterWatch.timeMs > 0 ? config.masterWatch.nodeId * 0x10000 + config.masterWatch.timeMs : 0
  rec(0x1016, [
    { sub: 0, attr: R, value: u8(1) },
    { sub: 1, attr: RW | MB, value: u32(watch) },
  ])
  v(0x1017, RW | MB, u16(config.heartbeatMs))
  rec(0x1018, [
    { sub: 0, attr: R, value: u8(4) },
    { sub: 1, attr: R | MB, value: u32(config.vendorId) },
    { sub: 2, attr: R | MB, value: u32(config.productCode) },
    { sub: 3, attr: R | MB, value: u32(config.revision) },
    { sub: 4, attr: R | MB, value: u32(config.lss?.serial ?? 0) },
  ])
  const coding = { pre_operational: 0, no_change: 1, stopped: 2, none: 1 } as const
  rec(0x1029, [
    { sub: 0, attr: R, value: u8(2) },
    { sub: 1, attr: RW, value: u8(coding[config.onMasterLost]) },
    { sub: 2, attr: RW, value: u8(coding[config.onPlcStopState]) },
  ])
  rec(0x1200, [
    { sub: 0, attr: R, value: u8(2) },
    { sub: 1, attr: R | MB, value: u32(0x600 + config.nodeId) },
    { sub: 2, attr: R | MB, value: u32(0x580 + config.nodeId) },
  ])
  for (const tpdo of [false, true]) {
    const list = tpdo ? pdos.tpdos : pdos.rpdos
    const commBase = tpdo ? 0x1800 : 0x1400
    const mapBase = tpdo ? 0x1a00 : 0x1600
    const cobBase = tpdo ? 0x180 : 0x200
    const used = list.filter((p) => p.objects.length > 0)
    for (let n = 1; n <= SLAVE_PDO_COUNT; n++) {
      const pdo = used.find((p) => p.number === n)
      const base = cobBase + 0x100 * (n - 1)
      let cob = pdo ? pdo.effectiveCobId : (COB_INVALID | (n <= 4 ? base : 0)) >>> 0
      if (pdo && cob === 0) cob = COB_INVALID
      if (pdo && n <= 4 && (cob & 0x7ff) === base + config.nodeId) cob = (cob & ~0x7ff) | base
      const subs: Sub[] = [
        { sub: 0, attr: R, value: u8(tpdo ? 6 : 5) },
        { sub: 1, attr: RW | MB, value: u32(cob) },
        { sub: 2, attr: RW, value: u8(pdo ? pdo.transmissionType : 255) },
      ]
      if (tpdo) {
        subs.push({ sub: 3, attr: RW | MB, value: u16(pdo ? pdo.inhibitTime : 0) })
        subs.push({ sub: 4, attr: RW, value: u8(0) })
      }
      subs.push({ sub: 5, attr: RW | MB, value: u16(pdo ? pdo.eventTimerMs : 0) })
      if (tpdo) subs.push({ sub: 6, attr: RW, value: u8(0) })
      rec(commBase + n - 1, subs)
    }
    for (let n = 1; n <= SLAVE_PDO_COUNT; n++) {
      const pdo = used.find((p) => p.number === n)
      const subs: Sub[] = [{ sub: 0, attr: RW, value: u8(pdo ? pdo.objects.length : 0) }]
      for (let s = 1; s <= 8; s++) {
        const o = pdo?.objects[s - 1]
        const map = o ? (o.index * 0x10000 + o.subIndex * 0x100 + slaveObjectBytes(o) * 8) >>> 0 : 0
        subs.push({ sub: s, attr: RW | MB, value: u32(map) })
      }
      rec(mapBase + n - 1, subs)
    }
  }
  return out.sort((a, b) => a.index - b.index)
}

function objectAttr(o: CanopenSlaveObject): number {
  let attr: number
  if (o.exchange === 'constant') attr = R
  else if (o.direction === 'from_master') attr = RW | (o.exchange === 'pdo' ? RPDO : 0)
  else attr = R | (o.exchange === 'pdo' ? TPDO : 0)
  return attr | (isSlaveString(o) ? STR : slaveObjectBytes(o) > 1 ? MB : 0)
}

const hex = (v: number, digits: number): string => `0x${v.toString(16).toUpperCase().padStart(digits, '0')}`

function cBytes(bytes: Iterable<number>): string {
  return [...bytes].map((b) => hex(b, 2)).join(', ')
}

function cString(text: string): string {
  return JSON.stringify(text)
}

export interface SlaveBoardHeaders {
  configH: string
  /** Absent when no slave is on. */
  odH?: string
}

/** The headers for the board's slave, or the disabled stub when no slave is on. */
export function generateSlaveBoardHeaders(
  slave: { name: string; config: CanopenSlaveConfig } | null,
  board: CanopenSlaveBoardProfile,
): SlaveBoardHeaders {
  if (!slave) return { configH: CANOPEN_SLAVE_CONFIG_DISABLED }
  const { name, config } = slave
  const layout = slavePdoLayout(config)
  const comm = commEntries(config, layout)

  // Application objects, grouped by index in ascending order.
  const objects = [...config.objects].sort((a, b) => a.index - b.index || a.subIndex - b.subIndex)
  const app: Entry[] = []
  for (const o of objects) {
    let entry = app.find((e) => e.index === o.index)
    if (!entry) {
      entry = { index: o.index, record: true, subs: [{ sub: 0, attr: R, value: u8(0) }] }
      app.push(entry)
    }
    entry.subs[0].value = u8(o.subIndex)
    const value = isSlavePacked(o)
      ? slaveRawBytes(o.defaultValue, 'UNSIGNED8')
      : slaveRawBytes(o.defaultValue, o.dataType)
    entry.subs.push({ sub: o.subIndex, attr: objectAttr(o), value })
  }

  // One data blob: every value at an offset aligned to its size, the communication objects first.
  let size = 0
  const offsets = new Map<Sub, number>()
  const place = (s: Sub): void => {
    const len = Math.max(1, s.value.length)
    const align = len >= 8 ? 8 : len >= 4 ? 4 : len >= 2 ? 2 : 1
    size = Math.ceil(size / align) * align
    offsets.set(s, size)
    size += len
  }
  for (const e of comm) e.subs.forEach(place)
  size = Math.ceil(size / 8) * 8
  const commBytes = size
  for (const e of app) e.subs.forEach(place)
  size = Math.max(8, Math.ceil(size / 8) * 8)
  const blob = new Uint8Array(size)
  for (const [s, off] of offsets) blob.set(s.value, off)

  const entries = [...comm, ...app].sort((a, b) => a.index - b.index)
  const lines: string[] = []
  const add = (...l: string[]): void => {
    lines.push(...l)
  }
  add(
    `// Generated by OpenPLC Editor: the object dictionary of CANopen slave ${cString(name)}.`,
    '// Included once, by canopen_slave.cpp, after CANopen.h.',
    '#ifndef CANOPEN_SLAVE_OD_H',
    '#define CANOPEN_SLAVE_OD_H',
    '',
    `#define CO_SLAVE_DATA_BYTES ${size}`,
    `#define CO_SLAVE_COMM_BYTES ${commBytes}`,
    '',
    'alignas(8) static uint8_t co_slave_data[CO_SLAVE_DATA_BYTES];',
    'static const uint8_t co_slave_defaults[CO_SLAVE_DATA_BYTES] = {',
  )
  for (let i = 0; i < blob.length; i += 16) add(`    ${cBytes(blob.subarray(i, i + 16))},`)
  add('};', '')
  for (const e of entries) {
    const id = e.index.toString(16).toUpperCase().padStart(4, '0')
    if (!e.record) {
      const s = e.subs[0]
      add(
        `static OD_obj_var_t co_slave_${id} = {&co_slave_data[${offsets.get(s)}], ${hex(s.attr, 2)}, ${s.value.length}};`,
      )
    } else {
      add(`static OD_obj_record_t co_slave_${id}[${e.subs.length}] = {`)
      for (const s of e.subs)
        add(`    {&co_slave_data[${offsets.get(s)}], ${s.sub}, ${hex(s.attr, 2)}, ${s.value.length}},`)
      add('};')
    }
  }
  add('', `static OD_entry_t co_slave_list[${entries.length + 1}] = {`)
  for (const e of entries) {
    const id = e.index.toString(16).toUpperCase().padStart(4, '0')
    const type = e.record ? 'ODT_REC' : 'ODT_VAR'
    add(`    {${hex(e.index, 4)}, ${e.subs.length}, ${type}, ${e.record ? '' : '&'}co_slave_${id}, NULL},`)
  }
  add('    {0x0000, 0, 0, NULL, NULL},', '};', `static OD_t co_slave_od = {${entries.length}, co_slave_list};`, '')

  // The application objects for the module: where each value is and which variables it goes to.
  const locations: Located[] = []
  const rows: string[] = []
  const appIndexes: string[] = []
  let first = 0
  for (const e of app) {
    const own = objects.filter((o) => o.index === e.index)
    appIndexes.push(`    {${hex(e.index, 4)}, ${first}, ${own.length}},`)
    first += own.length
    for (const o of own) {
      const sub = e.subs.find((s) => s.sub === o.subIndex)
      const off = sub ? (offsets.get(sub) ?? 0) : 0
      const locFirst = locations.length
      if (o.exchange !== 'constant') {
        const texts = isSlavePacked(o) ? (o.bits ?? []).map((b) => b.iecLocation) : [o.iecLocation]
        for (const t of texts) locations.push(parseSlaveLocation(t) ?? { area: 'I', size: 'X', index: 0xffff, bit: 0 })
      }
      const ranged = o.direction === 'from_master' && o.exchange !== 'constant' && !isSlavePacked(o)
      const hasMin = ranged && (o.min ?? '').trim() !== ''
      const hasMax = ranged && (o.max ?? '').trim() !== ''
      const raw = (t: string | undefined): string => {
        const b = slaveRawBytes(t ?? '0', o.dataType)
        let v = 0n
        for (let i = b.length - 1; i >= 0; i--) v = (v << 8n) | BigInt(b[i])
        return `0x${v.toString(16).toUpperCase()}ULL`
      }
      const flags = (hasMin ? 1 : 0) | (hasMax ? 2 : 0) | (isSlavePacked(o) ? 4 : 0)
      rows.push(
        `    {${hex(o.index, 4)}, ${o.subIndex}, ${o.direction === 'from_master' ? 0 : 1}, ${
          { pdo: 0, sdo: 1, constant: 2 }[o.exchange]
        }, ${TYPE_CODE[o.dataType]}, ${slaveObjectBytes(o)}, ${flags}, ${off}, ${locFirst}, ${
          locations.length - locFirst
        }, ${raw(hasMin ? o.min : undefined)}, ${raw(hasMax ? o.max : undefined)}},`,
      )
    }
  }
  add(
    `#define CO_SLAVE_OBJECTS ${rows.length}`,
    `#define CO_SLAVE_APP_INDEXES ${app.length}`,
    `#define CO_SLAVE_LOCATIONS ${locations.length}`,
    '',
    `static const co_slave_object_t co_slave_objects[${Math.max(1, rows.length)}] = {`,
    ...(rows.length ? rows : ['    {0, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0ULL, 0ULL},']),
    '};',
    `static const co_slave_app_index_t co_slave_app_indexes[${Math.max(1, app.length)}] = {`,
    ...(appIndexes.length ? appIndexes : ['    {0, 0, 0},']),
    '};',
    `static const co_slave_location_t co_slave_locations[${Math.max(1, locations.length)}] = {`,
    ...(locations.length
      ? locations.map((l) => `    {'${l.area}', '${l.size}', ${l.index}, ${l.bit}},`)
      : ["    {'I', 'X', 0xFFFF, 0},"]),
    '};',
    '',
    '#endif // CANOPEN_SLAVE_OD_H',
    '',
  )

  const kbit = Math.round(config.bitrate / 1000)
  const configH = [
    `// Generated by OpenPLC Editor: CANopen slave ${cString(name)} on the board's ${board.controller.toUpperCase()}.`,
    '#ifndef CANOPEN_SLAVE_CONFIG_H',
    '#define CANOPEN_SLAVE_CONFIG_H',
    '',
    '#define CANOPEN_SLAVE_ENABLED 1',
    `#define CANOPEN_SLAVE_NAME ${cString(name)}`,
    `#define CANOPEN_SLAVE_TX_PIN ${config.boardPins?.tx ?? board.txPin}`,
    `#define CANOPEN_SLAVE_RX_PIN ${config.boardPins?.rx ?? board.rxPin}`,
    `#define CANOPEN_SLAVE_KBIT ${kbit}`,
    `#define CANOPEN_SLAVE_NODE_ID ${config.nodeId}`,
    `#define CANOPEN_SLAVE_START_ALONE ${config.startAlone ? 1 : 0}`,
    `#define CANOPEN_SLAVE_ZERO_ON_PLC_STOP ${config.onPlcStop === 'zero' ? 1 : 0}`,
    `#define CANOPEN_SLAVE_MASTER_NODE_ID ${config.masterWatch.timeMs > 0 ? config.masterWatch.nodeId : 0}`,
    '',
    '#endif // CANOPEN_SLAVE_CONFIG_H',
    '',
  ].join('\n')
  return { configH, odH: lines.join('\n') }
}
